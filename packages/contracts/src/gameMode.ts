import type { Warehouse } from "./resources";

// Game modes (SETTLERS-PLAN.md §1). A mode is a STORED, per-game value --
// `games.lobby.gameMode` -- not a build-time flag and not a client setting:
// every mode-dependent rule reads this one value, and ABSENT reads as
// DEFAULT_GAME_MODE, so every game created before the feature keeps today's
// rules byte-for-byte. The lobby-jsonb carrier is the `lobby.uncharted` /
// `lobby.legacyAutoTrade` precedent: no column, no migration.
export const GAME_MODES = ["classic", "settlers"] as const;

export type GameMode = (typeof GAME_MODES)[number];

/** The mode an absent/unreadable `lobby.gameMode` resolves to. */
export const DEFAULT_GAME_MODE: GameMode = "classic";

export function isGameMode(value: unknown): value is GameMode {
  return typeof value === "string" && (GAME_MODES as readonly string[]).includes(value);
}

/**
 * Any stored or wire value -> a usable mode. Unknown junk (a legacy row, a
 * hand-edited lobby bag, a typo'd request body) reads as the default rather
 * than throwing: a game whose mode cannot be read is a classic game, never an
 * error the load path has to handle.
 */
export function resolveGameMode(value?: string | null): GameMode {
  return isGameMode(value) ? value : DEFAULT_GAME_MODE;
}

/**
 * The mode's settings keys. These are the ONLY place a mode tunable may be
 * declared: the engine reads them off the state's mode, the server reads them
 * for its creation-time seeding, the client reads them for the form's copy and
 * the tests assert against them. A second literal (a form default, an AI
 * threshold, a fixture) is a bug -- it is exactly the drift that makes a
 * "constant" a decoration.
 */
export interface GameModeSettings {
  /**
   * Q1: the founding wagon is consumed by the settlement it founds, so one
   * wagon buys exactly one settlement and the wagon pool is the expansion
   * budget. False = the wagon survives and can found again.
   */
  wagonConsumedOnFounding: boolean;
  /**
   * Q2: minimum axial hex distance (`hexDistance`, geometry.ts) a new
   * settlement must keep from EVERY settlement, neutral castles included.
   * 0 = no distance rule beyond not landing on an occupied settlement hex.
   */
  minFoundingDistance: number;
  /**
   * Q3: the cargo the founding wagon carries into the new settlement's
   * warehouse. All-zero = the settlement starts empty.
   */
  wagonSupplies: Warehouse;
  /**
   * Q3: whether founding grants the starter building layout for free. False
   * leaves the city view's existing free starter commit (settlement/
   * starterLayout.ts's starterCityOnOpen) as the only grant, so a new
   * settlement is not handed a city.
   */
  freeStarterBuildings: boolean;
  /**
   * Q4: neutral castles (ownerId null, generated by map/castlePlacement.ts)
   * still spawn in the wilderness. Suppressing them is a FILTER over the
   * generated PlacedCastle[] -- never a change to castlePlacement.ts's
   * candidate scan or draw order, which would move every settlement's
   * position and every seeded name/horse variant with it.
   */
  neutralCastles: boolean;
  /**
   * Q4: monster lairs still spawn in the wilderness. No lair generator exists
   * in the codebase yet, so this key is the mode's forward-looking answer and
   * is read by nothing today.
   */
  monsterLairs: boolean;
}

/**
 * Classic: the pre-feature rules. Founding goes through the charter path
 * (packages/engine/src/charter/**), which reads NONE of these keys -- they are
 * the neutral values that keep a classic game byte-identical, and the ones a
 * mode-blind rule falls back to.
 */
export const CLASSIC_MODE_DEFAULTS: GameModeSettings = {
  wagonConsumedOnFounding: false,
  minFoundingDistance: 0,
  wagonSupplies: { wood: 0, stone: 0, iron: 0, arcane: 0, food: 0 },
  freeStarterBuildings: true,
  neutralCastles: true,
  monsterLairs: true,
};

/**
 * Settlers: the mode's own rules. The four design answers in SETTLERS-PLAN.md
 * §3 are these keys -- flipping one here (plus its assertion) is the whole
 * change when the reader answers differently.
 */
export const SETTLERS_MODE_DEFAULTS: GameModeSettings = {
  wagonConsumedOnFounding: true,
  minFoundingDistance: 3,
  wagonSupplies: { wood: 200, stone: 100, iron: 50, arcane: 0, food: 50 },
  freeStarterBuildings: false,
  neutralCastles: true,
  monsterLairs: true,
};

export const GAME_MODE_SETTINGS: Record<GameMode, GameModeSettings> = {
  classic: CLASSIC_MODE_DEFAULTS,
  settlers: SETTLERS_MODE_DEFAULTS,
};

/** The settings keys for a mode; unknown/absent values read as the default mode. */
export function gameModeSettings(mode?: string | null): GameModeSettings {
  return GAME_MODE_SETTINGS[resolveGameMode(mode)];
}
