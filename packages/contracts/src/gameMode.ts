import type { Warehouse } from "./resources";

// Game modes (SETTLERS-PLAN.md §1). A mode is a STORED, per-game value --
// `games.lobby.gameMode` -- not a build-time flag and not a client setting:
// every mode-dependent rule reads this one value, and ABSENT reads as
// DEFAULT_GAME_MODE, so every game created before the feature keeps today's
// rules byte-for-byte. The lobby-jsonb carrier is the `lobby.uncharted` /
// `lobby.legacyAutoTrade` precedent: no column, no migration.
export const GAME_MODES = ["classic", "settlers"] as const;

export type GameMode = (typeof GAME_MODES)[number];

/** The mode an absent/unreadable `lobby.gameMode` resolves to. */
export const DEFAULT_GAME_MODE: GameMode = "classic";

export function isGameMode(value: unknown): value is GameMode {
  return typeof value === "string" && (GAME_MODES as readonly string[]).includes(value);
}

/**
 * Any stored or wire value -> a usable mode. Unknown junk (a legacy row, a
 * hand-edited lobby bag, a typo'd request body) reads as the default rather
 * than throwing: a game whose mode cannot be read is a classic game, never an
 * error the load path has to handle.
 */
export function resolveGameMode(value?: string | null): GameMode {
  return isGameMode(value) ? value : DEFAULT_GAME_MODE;
}

/**
 * The mode's settings keys. These are the ONLY place a mode tunable may be
 * declared: the engine reads them off the state's mode, the server reads them
 * for its creation-time seeding, the client reads them for the form's copy and
 * the tests assert against them. A second literal (a form default, an AI
 * threshold, a fixture) is a bug -- it is exactly the drift that makes a
 * "constant" a decoration.
 */
export interface GameModeSettings {
  /**
   * Q1: the founding wagon BECOMES the founded settlement's first hero --
   * one entity renamed in place (`p<seat>-wagon` -> `p<seat>-hero`), so the
   * wagon is not spent and the seat keeps a mobile entity. False = the wagon
   * is consumed by the town it founds (the mode's pre-conversion answer,
   * still the flip test's other half), leaving the seat with nothing mobile.
   */
  wagonBecomesFirstHero: boolean;
  /**
   * Q2: minimum axial hex distance (`hexDistance`, geometry.ts) a new
   * settlement must keep from EVERY settlement, neutral castles included.
   * 0 = no distance rule beyond not landing on an occupied settlement hex.
   */
  minFoundingDistance: number;
  /**
   * Q3: the cargo a seat's wagon starts with. It rides as the wagon's
   * `resources`; founding is what moves it (or leaves it aboard -- see
   * `cargoStaysWithFounderHero`).
   */
  wagonSupplies: Warehouse;
  /**
   * Q3: whether a founder that survives keeps its cargo. False = the founding
   * writes what the founder carries at that moment (`carriedSupplies`) into
   * the new town's warehouse and leaves the founder empty-handed: ONE
   * stockpile, in the town. True = the founder rides on with the load and the
   * town's warehouse starts empty.
   */
  cargoStaysWithFounderHero: boolean;
  /**
   * Q3: whether a settlement is ever handed the classic starter city for
   * free. It gates BOTH grants: the founding-time layout
   * (settlers/supplies.ts's foundedSettlementBuildings) and the city view's
   * free commit on first open (settlement/starterLayout.ts's
   * starterCityOnOpen). False = a founded settlement starts empty and stays
   * empty until the player places its buildings, paying for all but the free
   * town hall.
   */
  freeStarterBuildings: boolean;
  /**
   * Q4: neutral castles (ownerId null, generated by map/castlePlacement.ts)
   * spawn in the wilderness. Settlers answers NO -- bare wilderness means no
   * neutral towns, settlements or castles either -- and classic keeps today's
   * YES. Suppressing them is a FILTER over the generated PlacedCastle[] --
   * never a change to castlePlacement.ts's candidate scan or draw order,
   * which would move every settlement's position and every seeded
   * name/horse variant with it.
   */
  neutralCastles: boolean;
  /**
   * Q4: monster lairs still spawn in the wilderness. No lair generator exists
   * in the codebase yet, so this key is the mode's forward-looking answer and
   * is read by nothing today.
   */
  monsterLairs: boolean;
}

/**
 * Classic: the pre-feature rules. Founding goes through the charter path
 * (packages/engine/src/charter/**), which reads NONE of these keys -- they are
 * the neutral values that keep a classic game byte-identical, and the ones a
 * mode-blind rule falls back to.
 */
export const CLASSIC_MODE_DEFAULTS: GameModeSettings = {
  wagonBecomesFirstHero: false,
  minFoundingDistance: 0,
  wagonSupplies: { wood: 0, stone: 0, iron: 0, arcane: 0, food: 0 },
  cargoStaysWithFounderHero: false,
  freeStarterBuildings: true,
  neutralCastles: true,
  monsterLairs: true,
};

/**
 * Settlers: the mode's own rules, and the four confirmed intentions in one
 * place -- bare wilderness (`neutralCastles: false`), no prebuilt city ever
 * (`freeStarterBuildings: false`), founding in place on the wagon's own hex
 * (the rule below has no reach), and the wagon becoming the town's first hero
 * (`wagonBecomesFirstHero: true`) instead of being spent.
 *
 * Flipping one of these here (plus its assertion in
 * test/engine/settlersMode.test.ts) is the whole change when the reader
 * answers differently -- see the flip tests, which run the RULE rather than
 * reading the constant back.
 */
export const SETTLERS_MODE_DEFAULTS: GameModeSettings = {
  wagonBecomesFirstHero: true,
  minFoundingDistance: 3,
  wagonSupplies: { wood: 200, stone: 100, iron: 50, arcane: 0, food: 50 },
  cargoStaysWithFounderHero: false,
  freeStarterBuildings: false,
  neutralCastles: false,
  monsterLairs: true,
};

export const GAME_MODE_SETTINGS: Record<GameMode, GameModeSettings> = {
  classic: CLASSIC_MODE_DEFAULTS,
  settlers: SETTLERS_MODE_DEFAULTS,
};

/** The settings keys for a mode; unknown/absent values read as the default mode. */
export function gameModeSettings(mode?: string | null): GameModeSettings {
  return GAME_MODE_SETTINGS[resolveGameMode(mode)];
}

// ── The mode's starting entity: the covered wagon ──────────────────────────
//
// In settlers mode a seat does not start with a castle and a commander; it
// starts with ONE covered wagon in the wilderness, carrying the mode's
// `wagonSupplies`. Founding plants the settlement where the wagon stands and
// the wagon BECOMES that settlement's first hero (design answer 1): it is not
// deleted, its id is converted to the seat's hero id, and `players[].heroIds`
// is rewritten with it.
//
// The wagon is a HeroState -- the only entity the persistence layer has a home
// for (`games.heroes`, mirrored by the granular heroes table, and `players.
// heroIds`), and the reason "wagon movement and fog reveal like a hero" costs
// no new movement/vision code: the hero rules ARE its rules. Its identity is
// carried by its id, `p<seat>-wagon`, because the granulated heroes table has
// fixed columns and the mode may not add one (§2.5: no schema migration for
// the mode), so a per-entity boolean would not survive a reload. Every
// consumer -- the engine's placers, the server's founding case, the client's
// wagon rendering -- reads the id through these functions rather than
// re-spelling the suffix.
export const COVERED_WAGON_ID_SUFFIX = "-wagon";

/** The id suffix of a seat's own starting hero (`p<seat>-hero`) -- init.ts's makeHeroes, and the identity a founding wagon takes over. */
export const SEAT_HERO_ID_SUFFIX = "-hero";

/** The id of the covered wagon of seat `seat` (0-based player id). */
export function coveredWagonIdFor(seat: number): string {
  return `p${seat}${COVERED_WAGON_ID_SUFFIX}`;
}

/**
 * True when `id` is a covered wagon's id rather than a recruited hero's
 * (`h<n>`) or a seat's starting commander (`p<seat>-hero`). Suffix-based and
 * deliberately total: it is a naming convention, not a lookup, so it cannot
 * throw on a legacy id.
 */
export function isCoveredWagonId(id: string): boolean {
  return id.endsWith(COVERED_WAGON_ID_SUFFIX);
}

/** The id of seat `seat`'s own starting hero (`p<seat>-hero`). */
export function seatHeroIdFor(seat: number): string {
  return `p${seat}${SEAT_HERO_ID_SUFFIX}`;
}

/**
 * The seat a covered wagon id names, or null when `id` is not one.
 *
 * `isCoveredWagonId` is a suffix test and stays one (every mode gate wants a
 * cheap truth value); this is the PARSE beside it, for the one caller that has
 * to know WHICH seat a wagon belongs to -- founding's identity conversion. It
 * re-serializes the id rather than trusting `Number()` alone, so `p1-wagonx`
 * or `p-wagon` cannot masquerade as a seat.
 */
export function coveredWagonSeatOf(id: string): number | null {
  if (!isCoveredWagonId(id)) return null;
  const digits = id.slice(1, id.length - COVERED_WAGON_ID_SUFFIX.length);
  if (!/^\d+$/.test(digits)) return null;
  const seat = Number(digits);
  return Number.isSafeInteger(seat) && coveredWagonIdFor(seat) === id ? seat : null;
}

/**
 * The id a covered wagon takes when it becomes the settlement's first hero
 * (`wagonBecomesFirstHero`): the wagon of seat `seat` is the same entity as
 * `seatHeroIdFor(seat)`, so the conversion is a rename rather than a
 * delete-plus-create, and it is collision-free -- recruited heroes are `h<n>`
 * (hero/recruit.ts) and the only allocator of `p<seat>-hero` (init.ts's
 * makeHeroes) never runs in settlers mode.
 *
 * Null for an id that is not a wagon's, so a caller can test the conversion
 * with one call.
 */
export function coveredWagonHeroIdFor(id: string): string | null {
  const seat = coveredWagonSeatOf(id);
  return seat === null ? null : seatHeroIdFor(seat);
}
